async function setup(permissions = ['admin.files.view', 'admin.files.upload', 'admin.files.delete']) {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } }), page = await context.newPage()
  page.on('pageerror', error => errors.push(error.message))
  await context.route('**/api/public/v1/files/*', route => route.fulfill({ contentType: 'image/svg+xml', body: '<svg xmlns="http://www.w3.org/2000/svg" width="200" height="130"><rect width="200" height="130" rx="8" fill="#e9f2ff"/><circle cx="100" cy="65" r="38" fill="#a8cdff"/></svg>' }))
  await context.route('**/api/admin/v1/**', async route => {
    const url = new URL(route.request().url()), path = url.pathname.replace('/api/admin/v1', '')
    let data = []
    if (path === '/auth/me') data = { user: { id: 1, username: 'files', nickname: '文件管理员', is_founder: false, last_login_at: null }, permissions }
    else if (path === '/files/statistics') data = { count: files.length, byte_size: files.reduce((sum, file) => sum + file.byte_size, 0), types: types.map(type => ({ type, count: files.filter(file => file.type === type).length, byte_size: files.filter(file => file.type === type).reduce((sum, file) => sum + file.byte_size, 0) })) }
    else if (path === '/files') {
      let rows = files.filter(file => (!url.searchParams.get('type') || file.type === url.searchParams.get('type')) && (!url.searchParams.get('name') || file.original_name.includes(url.searchParams.get('name'))) && (!url.searchParams.get('origin') || file.origin === url.searchParams.get('origin')))
      if (url.searchParams.get('sort_by')) rows = rows.toSorted((a, b) => (a.byte_size - b.byte_size) * (url.searchParams.get('sort_order') === 'desc' ? -1 : 1))
      const current = Number(url.searchParams.get('page') ?? 1), pageSize = Number(url.searchParams.get('page_size') ?? 20)
      data = { data: rows.slice((current - 1) * pageSize, current * pageSize), total: rows.length, page: current, page_size: pageSize }
    }
    await route.fulfill({ json: { code: 0, message: 'ok', data, request_id: 'files-browser' } })
  })
  await page.goto(`${base}/content/files`)
  await page.getByRole('article').first().waitFor()
  return { context, page }
}
